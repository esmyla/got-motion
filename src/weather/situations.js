const CUSTOM_CONDITIONS = [
  'Mostly Awkward',
  'Partly Awkward',
  'Scattered Glances',
  'Patchy Silence',
  'Isolated Small Talk',
  'Increasing Dread',
  'Vibes Unclear',
];
const CUSTOM_CITIES = ['Nashville', 'Omaha', 'Tucson', 'Raleigh', 'Tulsa', 'Boise', 'Albany', 'Reno'];
const CUSTOM_SKIES = ['cloudy', 'night', 'rain', 'sunny', 'wind', 'overcast', 'fog', 'sunset'];
const DIRECTIONS = ['N', 'NE', 'E', 'SE', 'S', 'SW', 'W', 'NW'];

/** Builds a full forecast for any situation someone types in. */
export function makeCustomPlace(rawName) {
  const typed = rawName.trim().replace(/\s+/g, ' ').slice(0, 26);
  // "dentist" becomes "Dentist"; anything typed with its own capitals is left alone.
  const name = typed === typed.toLowerCase() ? typed.replace(/(^|\s)\p{L}/gu, (ch) => ch.toUpperCase()) : typed;
  const rand = seeded(`custom:${name.toLowerCase()}`);
  const temp = rand.int(58, 84);
  const spread = rand.int(2, 9);
  return {
    id: `custom-${hashString(name.toLowerCase()).toString(36)}`,
    custom: true,
    name,
    where: 'Added by you, for some reason',
    city: rand.pick(CUSTOM_CITIES),
    sky: rand.pick(CUSTOM_SKIES),
    cond: rand.pick(CUSTOM_CONDITIONS),
    temp,
    hi: temp + spread,
    lo: temp - spread,
    summary: 'Conditions here are expected to stay exactly this uncomfortable through the evening.',
    cards: {
      eye: [rand.int(5, 10), 'Look at your phone until this is over.'],
      exit: [`${rand.int(6, 10)}:${rand.pick(['00', '15', '30', '45'])}PM`, 'The earliest you can leave without it being a whole thing.'],
      air: [rand.int(4, 28), rand.pick(DIRECTIONS), 'Someone nearby has a long story and no ending.'],
      talk: [rand.int(40, 95), '“Crazy weather, huh?” is likely. Ironic.'],
      feels: [temp + rand.int(6, 16), 'Warmer than it is, mostly around the ears.'],
      palm: [rand.int(48, 92), 'Keep both hands on the phone.'],
      vis: [rand.int(2, 10), null, 'You can be seen from most of the room.'],
      pressure: [Number(rand.range(30.1, 31.4).toFixed(2)), 'up', 'Rising. Somebody is about to ask you something.'],
      aqi: [rand.int(35, 140), 'A smell you cannot place and will not ask about.'],
      battery: [rand.int(11, 60), 'Draining. Does not recharge in company.'],
    },
  };
}
